//What is the DOM?:-When a web page loads, the browser converts all your HTML into a tree-like structure called the DOM (Document Object Model).
/**
 | Method                     | Example                                   | Description        |
| -------------------------- | ----------------------------------------- | ------------------ |
| `getElementById()`         | `document.getElementById("title")`        | Select by ID       |
| `getElementsByClassName()` | `document.getElementsByClassName("info")` | Select by class    |
| `getElementsByTagName()`   | `document.getElementsByTagName("p")`      | Select by tag      |
| `querySelector()`          | `document.querySelector(".info")`         | Select first match |
| `querySelectorAll()`       | `document.querySelectorAll("p")`          | Select all matches |



 */